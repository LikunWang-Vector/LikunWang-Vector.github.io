const loadedScripts = new Map<string, Promise<void>>();

function loadScript(src: string): Promise<void> {
  const cached = loadedScripts.get(src);
  if (cached) return cached;
  const promise = new Promise<void>((resolve, reject) => {
    const script = document.createElement('script');
    script.src = src;
    script.async = false;
    script.dataset.mascotVendor = '1';
    script.addEventListener('load', () => resolve(), { once: true });
    script.addEventListener(
      'error',
      () => reject(new Error(`Could not load ${src}`)),
      { once: true },
    );
    document.head.append(script);
  });
  loadedScripts.set(src, promise);
  return promise;
}

let tickerRegistered = false;

async function loadRuntime(): Promise<any> {
  await loadScript(VENDOR('pixi.min.js'));
  await loadScript(VENDOR('live2dcubismcore.min.js'));
  await loadScript(VENDOR('cubism4.min.js'));

  const pixi = window.PIXI;
  if (!pixi?.live2d?.Live2DModel) throw new Error('Live2D runtime unavailable');
  if (!tickerRegistered) {
    pixi.live2d.Live2DModel.registerTicker(pixi.Ticker);
    tickerRegistered = true;
  }
  return pixi;
}

const clamp = (value: number): number => Math.max(-1, Math.min(1, value));

export async function createLive2DActor(
  host: HTMLElement,
  colour: MascotColour,
  reduced: boolean,
  profile: Live2DProfile,
): Promise<MascotActor> {
  const PIXI = await loadRuntime();

  // The host is measured after layout; switching forms resizes it, so wait a
  // frame before creating the renderer at the right size.
  await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()));
  const width = Math.max(host.clientWidth, 240);
  const height = Math.max(host.clientHeight, 240);

  const app = new PIXI.Application({
    width,
    height,
    backgroundColor: 0x000000,
    backgroundAlpha: 0,
    antialias: true,
    autoDensity: true,
    resolution: Math.min(window.devicePixelRatio || 1, 1.75),
    powerPreference: 'low-power',
  });
  app.renderer.transparent = true;
  app.ticker.maxFPS = 30;
  (app.view as HTMLCanvasElement).setAttribute('aria-hidden', 'true');
  (app.view as HTMLCanvasElement).style.opacity = '0';
  host.append(app.view);

  const { Live2DModel } = PIXI.live2d;
  let model: any;
  try {
    const options: Record<string, unknown> = { autoInteract: false, autoUpdate: true };
    // Expression-only rigs (中肥鱼 / 成年肥鱼) have no motions; passing a
    // missing idle group makes the runtime log a warning on every frame.
    if (profile.idleGroup) options.idleMotionGroup = profile.idleGroup;
    model = await Live2DModel.from(profile.modelUrl, options);
  } catch (error) {
    app.destroy(true, { children: true, texture: true, baseTexture: true });
    throw error;
  }
  model.interactive = false;
  model.buttonMode = false;
  model.anchor.set(0.5, 0.5);
  app.stage.addChild(model);

  const baseWidth = model.width;
  const baseHeight = model.height;

  const fit = (): void => {
    const nextWidth = host.clientWidth;
    const nextHeight = host.clientHeight;
    if (!nextWidth || !nextHeight) return;
    app.renderer.resize(nextWidth, nextHeight);
    const scale = Math.min(nextWidth / baseWidth, nextHeight / baseHeight) * (profile.zoom ?? 1.02);
    model.scale.set(scale);
    model.position.set(nextWidth / 2, nextHeight / 2);
  };

  const observer = new ResizeObserver(fit);
  observer.observe(host);
  fit();

  const core = model.internalModel.coreModel;
  const parameterIds = new Set<string>();
  const ids: string[] = core._parameterIds ?? [];
  for (const id of ids) parameterIds.add(id);
  if (!parameterIds.size && typeof core.getParameterCount === 'function') {
    for (let i = 0; i < core.getParameterCount(); i += 1) {
      const id = core.getParameterIdByIndex?.(i);
      if (id) parameterIds.add(id);
    }
  }

  const setParameter = (id: string | undefined, value: number): void => {
    if (!id || !parameterIds.has(id)) return;
    core.setParameterValueById(id, value);
  };

  let isReduced = reduced;
  let isActive = true;
  let targetX = 0;
  let targetY = 0;
  let currentX = 0;
  let currentY = 0;

  const applyRig = (): void => {
    const ease = isReduced ? 1 : 0.16;
    currentX += (targetX - currentX) * ease;
    currentY += (targetY - currentY) * ease;
    const rig = profile.rig;
    const amp = profile.amplitude;
    let swayZ = 0;
    let swayX = 0;
    if (profile.sway && !isReduced) {
      const t = (performance.now() / 1000) * profile.sway.speed;
      swayZ = Math.sin(t) * profile.sway.angleZ;
      swayX = Math.sin(t * 0.73 + 1.1) * profile.sway.bodyX;
    }
    setParameter(rig.angleX, currentX * amp.x1);
    setParameter(rig.angleX2, currentX * amp.x2);
    setParameter(rig.angleY, -currentY * amp.y1);
    setParameter(rig.angleY2, -currentY * amp.y2);
    setParameter(rig.angleZ, -currentX * amp.z1 + swayZ);
    setParameter(rig.angleZ2, -currentX * amp.z2);
    setParameter(rig.bodyX, currentX * amp.body + swayX);
    setParameter(rig.bodyY, -currentY * (amp.body / 2));
    setParameter(rig.eyeX, currentX * amp.eye);
    setParameter(rig.eyeY, -currentY * amp.eye);
    if (profile.baseParameters) {
      for (const [id, value] of Object.entries(profile.baseParameters)) {
        setParameter(id, value);
      }
    }
  };
  model.internalModel.on('beforeModelUpdate', applyRig);
  // When motion is reduced the ticker is stopped before the model ever
  // updates, so per-frame overrides (such as hiding the 中肥鱼 watermark)
  // would miss the first paint. Apply the base rig once up front.
  applyRig();

  const originalTextures: any[] = model.textures.slice();
  let activeVariant: { textures: any[] } | null = null;
  let currentColour: MascotColour = 'blue';
  let colourToken = 0;

  const applyTextures = (textures: any[]): void => {
    for (let i = 0; i < model.textures.length; i += 1) {
      if (textures[i]) model.textures[i] = textures[i];
    }
  };

  // The Cubism renderer uploads model.textures during Live2DModel._render. When
  // motion is reduced (or the actor is hidden) our ticker is stopped, so a
  // colour swap would otherwise never reach the GPU. Paint a single frame.
  const paintOnce = (): void => {
    if (!app.ticker.started) app.renderer.render(app.stage);
  };

  const loadVariant = async (next: MascotColour): Promise<any[]> =>
    Promise.all(profile.textures[next].map((url) => PIXI.Texture.fromURL(url)));

  const selectColour = async (next: MascotColour, initial = false): Promise<void> => {
    if (next === currentColour) {
      if (initial) (app.view as HTMLCanvasElement).style.opacity = '1';
      return;
    }
    const token = ++colourToken;

    if (next === 'blue') {
      applyTextures(originalTextures);
      if (activeVariant) {
        for (const texture of activeVariant.textures) texture.destroy(true);
        activeVariant = null;
      }
      currentColour = 'blue';
      paintOnce();
      (app.view as HTMLCanvasElement).style.opacity = '1';
      return;
    }

    try {
      const textures = await loadVariant(next);
      if (token !== colourToken) {
        for (const texture of textures) texture.destroy(true);
        return;
      }
      applyTextures(textures);
      if (activeVariant) {
        for (const texture of activeVariant.textures) texture.destroy(true);
      }
      activeVariant = { textures };
      currentColour = next;
      paintOnce();
      (app.view as HTMLCanvasElement).style.opacity = '1';
    } catch (error) {
      console.warn('[mascot] could not load the Live2D colourway', error);
      (app.view as HTMLCanvasElement).style.opacity = '1';
    }
  };

  // Paint the requested colour before the actor is revealed, so the poster
  // and the model never disagree for more than a frame.
  await selectColour(colour, true);
  if (colour === 'blue') (app.view as HTMLCanvasElement).style.opacity = '1';

  let expressionToken = 0;
  let expressionTimer = 0;
  let actionTimer = 0;

  const resetExpression = (): void => {
    const manager = model.internalModel.motionManager.expressionManager;
    if (manager?.resetExpression) manager.resetExpression();
    else model.expression();
  };

  const showExpression = (name: string, hold = 4200): void => {
    const token = ++expressionToken;
    try {
      void Promise.resolve(model.expression(name)).catch((error: unknown) => {
        console.warn('[mascot] could not play the expression', name, error);
      });
    } catch (error) {
      console.warn('[mascot] could not play the expression', name, error);
      return;
    }
    window.clearTimeout(expressionTimer);
    expressionTimer = window.setTimeout(() => {
      if (token === expressionToken) resetExpression();
    }, hold);
  };

  const syncTicker = (): void => {
    const running = isActive && !isReduced;
    // `autoUpdate` listens on PIXI's shared ticker; turn it off together with
    // our renderer so a hidden/frozen mascot costs no per-frame CPU.
    model.autoUpdate = running;
    if (running) {
      app.ticker.start();
    } else {
      app.ticker.stop();
      app.renderer.render(app.stage);
    }
  };

  syncTicker();

  return {
    setColour(next: MascotColour): void {
      void selectColour(next);
    },

    setGaze(x: number, y: number): void {
      if (isReduced) return;
      targetX = clamp(x);
      targetY = clamp(y);
    },

    play(action: MascotAction): void {
      if (isReduced) return;
      const entry = profile.actions[action];
      if (!entry) return;
      window.clearTimeout(actionTimer);
      try {
        if (entry.motion) model.motion(entry.motion, entry.index, 3);
      } catch (error) {
        console.warn('[mascot] could not play the motion', action, error);
      }
      if (entry.expression) showExpression(entry.expression, entry.hold ?? 4200);
      if (entry.hold) {
        actionTimer = window.setTimeout(() => {
          if (isReduced) return;
          try {
            model.internalModel.motionManager.stopAllMotions();
          } catch {
            /* already stopped */
          }
          resetExpression();
        }, entry.hold);
      }
    },

    setReduced(next: boolean): void {
      isReduced = next;
      if (next) {
        window.clearTimeout(actionTimer);
        targetX = 0;
        targetY = 0;
        currentX = 0;
        currentY = 0;
        model.internalModel.motionManager.stopAllMotions();
        resetExpression();
      }
      syncTicker();
    },

    setActive(next: boolean): void {
      isActive = next;
      syncTicker();
    },

    destroy(): void {
      window.clearTimeout(expressionTimer);
      window.clearTimeout(actionTimer);
      colourToken += 1;
      observer.disconnect();
      model.internalModel.off('beforeModelUpdate', applyRig);
      app.destroy(true, { children: true, texture: true, baseTexture: true });
      const leftovers = [...originalTextures, ...(activeVariant?.textures ?? [])];
      for (const texture of leftovers) {
        if (texture?.baseTexture) {
          try {
            texture.destroy(true);
          } catch {
            /* already released by the app */
          }
        }
      }
    },
  };
}
