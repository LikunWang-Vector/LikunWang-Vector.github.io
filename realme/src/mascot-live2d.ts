/**
 * Live2D actors for the accepted whale-girl forms.
 *
 *   maid  three presentation modes of the same maid design:
 *           standard  中肥鱼, the standard short-dress maid, by Mao绒绒家园
 *           adult     成年肥鱼, the mature long-dress maid, by 玹乐喵
 *           q         c_0120 “DeepSeek 鲸鱼娘”, the Q desk model by 氵六青
 *   chibi the small Q-version Live2D “大肥鱼” by 狐宫静, distributed as a public
 *         free model. It is an independent model, not a scaled copy of c_0120;
 *         the jinglan sprite sheet is the default Q look and the fallback.
 *
 * The standard and adult rigs have no motion clips, so their reactions are
 * expressions and the player adds a small procedural sway instead of an idle
 * motion. Their art is used under the non-commercial CC terms described in the
 * README; attribution stays in the wardrobe and the documentation.
 *
 * Runtime: PIXI 6 + pixi-live2d-display 0.4 + Live2D Cubism Core 5 (see
 * public/mascot/vendor for the licence notes). The vendor bundles are loaded
 * on demand so the first paint only pays for the static poster image.
 *
 * Colourways: the rig's own renderer bypasses PIXI filters, so the green/red
 * variants are pre-tinted texture atlases (generated by a one-off conversion
 * script) that are swapped into model.textures. Only blue-hued pixels move;
 * skin, line art, props and the white apron stay identical to the blue
 * original.
 */
import type { MascotAction, MascotActor, MascotColour } from './mascot-types';

/* PIXI and the Cubism core are UMD globals installed by the vendor scripts. */
declare global {
  interface Window {
    PIXI?: any;
  }
}

const VENDOR = (name: string): string => `${import.meta.env.BASE_URL}mascot/vendor/${name}`;
const LIVE2D = (name: string): string => `${import.meta.env.BASE_URL}mascot/live2d/${name}`;

export interface Live2DAction {
  motion?: string;
  /** Motion index inside the group; omitted means “let the runtime choose”. */
  index?: number;
  expression?: string;
  /** Keep a looping motion/expression for this long, then return to idle. */
  hold?: number;
}

export interface Live2DRig {
  angleX: string;
  angleY: string;
  angleZ: string;
  angleX2?: string;
  angleY2?: string;
  angleZ2?: string;
  bodyX: string;
  bodyY: string;
  eyeX: string;
  eyeY: string;
}

export interface Live2DProfile {
  modelUrl: string;
  textures: Record<MascotColour, string[]>;
  /** Idle motion group; omitted for expression-only rigs with no motions. */
  idleGroup?: string;
  /** Extra magnification on top of the fit; the Q rig reads better slightly larger. */
  zoom?: number;
  rig: Live2DRig;
  /** Peak parameter offsets at full pointer deflection. */
  amplitude: {
    x1: number;
    x2: number;
    y1: number;
    y2: number;
    z1: number;
    z2: number;
    body: number;
    eye: number;
  };
  /** Parameters forced every frame; used to hide the 中肥鱼 watermark. */
  baseParameters?: Record<string, number>;
  /** Slow idle sway for expression-only rigs that have no motion clips. */
  sway?: { angleZ: number; bodyX: number; speed: number };
  actions: Partial<Record<MascotAction, Live2DAction>>;
}

